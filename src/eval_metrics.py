import json
import math
from pathlib import Path

ROOT      = Path(__file__).resolve().parent.parent
RUNS_DIR  = ROOT / "runs"
EVAL_DIR  = ROOT / "data" / "eval"
REPORTS   = ROOT / "reports"


# ---------------------------------------------------------------------------
# Hand-implemented metric functions (B8, Step 1)
# ---------------------------------------------------------------------------

def precision_at_k(ranked: list[str], rels: dict[str, int], k: int = 5) -> float:
    """P@k: fraction of top-k results that are relevant (label >= 1)."""
    if k == 0:
        return 0.0
    return sum(1 for d in ranked[:k] if rels.get(d, 0) >= 1) / k


def mrr(ranked: list[str], rels: dict[str, int]) -> float:
    """MRR: reciprocal rank of the first relevant result."""
    for i, d in enumerate(ranked, 1):
        if rels.get(d, 0) >= 1:
            return 1.0 / i
    return 0.0


def ndcg_at_k(ranked: list[str], rels: dict[str, int], k: int = 10) -> float:
    """
    nDCG@k using **linear gain** (gain = label value: 0, 1, or 2).
    This matches ranx's default ndcg@k (not ndcg_burges which uses 2^rel - 1).
    Documents without a label count as 0 (pooling assumption).
    """
    dcg  = sum(rels.get(d, 0) / math.log2(i + 1)
               for i, d in enumerate(ranked[:k], 1))
    ideal = sorted(rels.values(), reverse=True)[:k]
    idcg = sum(r / math.log2(i + 1) for i, r in enumerate(ideal, 1))
    return dcg / idcg if idcg > 0 else 0.0


# ---------------------------------------------------------------------------
# Aggregate over all queries
# ---------------------------------------------------------------------------

def evaluate_run(run: dict[str, dict[str, float]],
                 qrels: dict[str, dict[str, int]]) -> dict[str, float]:
    """
    Compute average P@5, nDCG@10, MRR for a run.
    run:   {qid: {doc_id: score}}
    qrels: {qid: {doc_id: label}}
    """
    p5_list, ndcg_list, mrr_list = [], [], []
    for qid, scores in run.items():
        if qid not in qrels:
            continue
        ranked = sorted(scores, key=lambda d: scores[d], reverse=True)
        rels   = qrels[qid]
        p5_list.append(precision_at_k(ranked, rels, k=5))
        ndcg_list.append(ndcg_at_k(ranked, rels, k=10))
        mrr_list.append(mrr(ranked, rels))
    n = len(p5_list) or 1
    return {
        "P@5":      round(sum(p5_list) / n, 4),
        "nDCG@10":  round(sum(ndcg_list) / n, 4),
        "MRR":      round(sum(mrr_list) / n, 4),
        "n_queries": len(p5_list),
    }


# ---------------------------------------------------------------------------
# Full comparison table (B8, Step 3)
# ---------------------------------------------------------------------------

def compare_all_systems(qrels_path: Path | None = None) -> None:
    """
    Load all run files in runs/ and qrels, print + save comparison table.
    """
    import pandas as pd

    qrels_path = qrels_path or (EVAL_DIR / "qrels.json")
    if not qrels_path.exists():
        print(f"qrels not found: {qrels_path}. Build labels first (B7).")
        return

    with open(qrels_path) as f:
        qrels = json.load(f)

    rows = []
    for run_path in sorted(RUNS_DIR.glob("*.json")):
        with open(run_path) as f:
            run = json.load(f)
        metrics = evaluate_run(run, qrels)
        metrics["system"] = run_path.stem
        rows.append(metrics)

    df = pd.DataFrame(rows).set_index("system")
    print("\n=== Retrieval Evaluation ===")
    print(df.to_string())

    REPORTS.mkdir(exist_ok=True)
    out_md = REPORTS / "retrieval_eval.md"
    with open(out_md, "w") as f:
        f.write("# Retrieval Evaluation Results\n\n")
        f.write("> Auto-generated by `src/eval_metrics.py`\n\n")
        f.write(df.to_markdown())
        f.write("\n\n## Notes\n- Relevant = label ≥ 1 (strict: label = 2)\n")
        f.write("- nDCG uses linear gain (matches ranx default)\n")
        f.write("- Pooled labels; unjudged docs treated as non-relevant\n")
    print(f"\nSaved → {out_md}")


# ---------------------------------------------------------------------------
# Self-test against ranx (B8, Step 2)
# ---------------------------------------------------------------------------

def self_test():
    """Quick sanity check: compare hand metrics against ranx on a toy example."""
    try:
        from ranx import Qrels, Run, evaluate
    except ImportError:
        print("ranx not installed — skipping cross-check.")
        return

    qrels_dict = {"q1": {"d1": 2, "d2": 1, "d3": 0, "d4": 0}}
    run_dict   = {"q1": {"d1": 0.9, "d2": 0.7, "d3": 0.5, "d4": 0.3}}

    ranked = sorted(run_dict["q1"], key=lambda d: run_dict["q1"][d], reverse=True)
    rels   = qrels_dict["q1"]

    hand = {
        "P@5":     precision_at_k(ranked, rels, 5),
        "nDCG@10": ndcg_at_k(ranked, rels, 10),
        "MRR":     mrr(ranked, rels),
    }

    ranx_result = evaluate(Qrels(qrels_dict), Run(run_dict),
                           ["precision@5", "ndcg@10", "mrr"])

    print("Hand metrics:", hand)
    print("ranx metrics:", dict(ranx_result))

    tol = 1e-4
    ok = True
    for hand_key, ranx_key in [("P@5", "precision@5"), ("nDCG@10", "ndcg@10"), ("MRR", "mrr")]:
        diff = abs(hand[hand_key] - float(ranx_result[ranx_key]))
        if diff > tol:
            print(f"❌  {hand_key} mismatch: hand={hand[hand_key]}, ranx={ranx_result[ranx_key]}")
            ok = False
    if ok:
        print("✅  All hand metrics match ranx (within tolerance).")


if __name__ == "__main__":
    self_test()
    compare_all_systems()
